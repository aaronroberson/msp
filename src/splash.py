def make_splash(mode: str = "CLI") -> str:
    label = "M|S|P| |C|L|I" if mode == "CLI" else "M|S|P| |T|U|I"
    return f"""
          .---------------.
         /   ___________   \\
        |   /           \\   |
        |  |             |  |
        |   \\___________/   |
     .══╩═══════════════════╩══.
     ║                         ║
     ║    ╔═══════════════╗    ║
     ║    ║ {label} ║    ║
     ║    ╚═══════════════╝    ║
     ║                         ║
     ╚═════════════════════════╝
"""
