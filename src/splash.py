def make_splash(mode: str = "CLI") -> str:
    parts = ("M", "S", "P", " ", "C", "L", "I") if mode == "CLI" else ("M", "S", "P", " ", "T", "U", "I")
    label = "│ " + " │ ".join(parts) + " │"
    return f"""
            .─────────────────────────.
           /    _________________________    \\
          |   /                         \\   |
          |  |                              |  |
          |   \\________________________________/   |
  .══╩═══════════════════════════════════════════╩══.
     ║                                              ║
     ║     ┌───┬───┬───┬───┬───┬───┬───┐           ║
     ║     {label}           ║
     ║     └───┴───┴───┴───┴───┴───┴───┘           ║
     ║                                              ║
     ╚══════════════════════════════════════════════╝
"""
